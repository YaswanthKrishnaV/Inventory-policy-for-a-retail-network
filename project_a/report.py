"""Results tables and figures for Project A (numbers quoted in memo_A come from here)."""
from __future__ import annotations

import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from . import stress
from .src.config import path

SERIES = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]
INK, MUTED, GRID = "#1f1f1e", "#6b6a63", "#e6e5e0"


def _style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(MUTED)
    ax.tick_params(colors=MUTED, labelsize=8)
    ax.grid(axis="y", color=GRID, lw=0.6)
    ax.set_axisbelow(True)


def policy_table(runs: dict, target: float) -> pd.DataFrame:
    rows = []
    for name, (df, _) in runs.items():
        rows.append(dict(policy=name, n=len(df),
                         cost=df.total_cost.mean(), cost_p05=df.total_cost.quantile(.05), cost_p95=df.total_cost.quantile(.95),
                         fill=df.fill_rate.mean(), fill_p05=df.fill_rate.quantile(.05), fill_p95=df.fill_rate.quantile(.95),
                         p_fill_ok=(df.fill_rate >= target).mean(), fill_item_avg=df.fill_item_avg.mean(),
                         lost=df.cost_lost.mean(), holding=df.cost_holding_store.mean() + df.cost_holding_dc.mean(),
                         holding_dc=df.cost_holding_dc.mean(), transfer=df.cost_transfer.mean(), po=df.cost_po.mean(),
                         fill_F1=df.fill_FOODS_1.mean(), fill_F2=df.fill_FOODS_2.mean(), fill_F3=df.fill_FOODS_3.mean(),
                         ending_inv=df.ending_inventory_value.mean(),
                         violations=float(df[[c for c in df.columns if c.startswith("viol_")]].sum(1).mean())))
    return pd.DataFrame(rows).set_index("policy")


def write(cutoff, cfg, net, runs, st_out, st_daily, st_bl, knobs, blocks, frame, timings):
    rep = path(cfg, "reports_dir")
    target = cfg["fill_rate"]["target"]
    tab = policy_table(runs, target)
    st_tab = stress.summarise(st_out)
    st_bl_tab = stress.summarise(st_bl)
    base, rate, cen = frame
    out = dict(cutoff=cutoff, test_window=[cutoff + 1, cutoff + net.days], knobs=knobs, timings_s=timings,
               dc_outbound_cap=net.dc_out_cap, policies=tab.reset_index().to_dict("records"),
               stress_recommended=st_tab.reset_index().to_dict("records"),
               stress_baseline=st_bl_tab.reset_index().to_dict("records"),
               test_demand_units_recorded_basis=float(base.sum()), censored_cells=int(cen.sum()))
    (rep / f"results_{cutoff}.json").write_text(json.dumps(out, indent=1, default=float))

    f = lambda v: f"${v:,.0f}"
    p = lambda v: f"{100 * v:.1f}%"
    md = [f"# Project A results — cutoff d_{cutoff} (test d_{cutoff + 1}–d_{cutoff + net.days})", "",
          f"Monte Carlo over lead-time draws and censored-day demand draws; {int(tab.loc['recommended', 'n'])} runs per policy "
          f"(sensitivity rows fewer). Ranges are 5th–95th percentiles. Generated by `python -m project_a.run_project_a`.", "",
          "## Policies", "",
          "| policy | total cost (mean) | 5–95% | fill rate | 5–95% | P(fill ≥ 95%) | lost | holding | transfer | PO | ending inventory |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, r in tab.iterrows():
        md.append(f"| {name} | {f(r.cost)} | {f(r.cost_p05)}–{f(r.cost_p95)} | {p(r.fill)} | {p(r.fill_p05)}–{p(r.fill_p95)} | "
                  f"{r.p_fill_ok:.2f} | {f(r.lost)} | {f(r.holding)} | {f(r.transfer)} | {f(r.po)} | {f(r.ending_inv)} |")
    md += ["", "Fill by department (mean): " + "; ".join(
        f"{n}: {p(r.fill_F1)} / {p(r.fill_F2)} / {p(r.fill_F3)}" for n, r in tab.iterrows() if not n.startswith("sensitivity")),
        "", f"Rule violations cut by the simulator (mean per run): " + ", ".join(f"{n}: {r.violations:.0f}" for n, r in tab.iterrows()), "",
        f"Knobs used: `{json.dumps(knobs)}`", "",
        "## Stress test — FOODS_3 lead times x2 for POs placed in weeks 3–5", "",
        "| scenario | policy | cost | 5–95% | Δ cost vs base | fill | Δ fill | FOODS_3 fill | DC holding | ending inventory |",
        "|---|---|---|---|---|---|---|---|---|---|"]
    for lbl, t in (("recommended", st_tab), ("baseline", st_bl_tab)):
        for name, r in t.iterrows():
            md.append(f"| {name} | {lbl} | {f(r.cost_mean)} | {f(r.cost_p05)}–{f(r.cost_p95)} | {f(r.delta_cost_vs_base)} | {p(r.fill_mean)} | "
                      f"{100 * r.delta_fill_vs_base:+.1f} pts | {p(r.fill_FOODS_3)} | {f(r.holding_dc)} | {f(r.ending_inventory)} |")
    md += ["", "Runtime (s): " + ", ".join(f"{k} {v:.0f}" for k, v in timings.items()), "",
           "![](fig_policy_costs.png)", "", "![](fig_daily_fill.png)", "", "![](fig_stress.png)", ""]
    (rep / f"results_{cutoff}.md").write_text("\n".join(md))

    # figures --------------------------------------------------------------
    main = [n for n in tab.index if not n.startswith("sensitivity")]
    fig, ax = plt.subplots(figsize=(9, 0.55 * len(main) + 1.2))
    comp = [("lost", "lost sales"), ("holding", "holding"), ("transfer", "DC→store transfers"), ("po", "POs")]
    left = np.zeros(len(main))
    for k, (col, lbl) in enumerate(comp):
        v = tab.loc[main, col].to_numpy()
        ax.barh(range(len(main)), v, left=left, color=SERIES[k], height=0.6, label=lbl, edgecolor="white", linewidth=2)
        left += v
    for i, n in enumerate(main):
        ax.text(left[i] + 1500, i, f"${left[i] / 1000:,.0f}k · fill {100 * tab.loc[n, 'fill']:.1f}%", va="center", fontsize=8, color=INK)
    ax.set_yticks(range(len(main)), main, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlim(0, left.max() * 1.35)
    ax.set_title(f"Expected 56-day cost by component (cutoff d_{cutoff})", loc="left", fontsize=10, color=INK)
    ax.legend(frameon=False, fontsize=8, ncol=4, loc="lower right")
    _style(ax); ax.grid(axis="x", color=GRID, lw=0.6); ax.grid(axis="y", visible=False)
    fig.tight_layout(); fig.savefig(rep / "fig_policy_costs.png", dpi=140); plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 3.4))
    for k, n in enumerate(["baseline", "recommended"]):
        d = runs[n][1]["daily"]
        fr = 1 - np.array(d["lost"]) / np.maximum(np.array(d["demand"]), 1)
        ax.plot(np.arange(1, len(fr) + 1), 100 * fr, color=SERIES[k], lw=2, label=n)
    ax.axhline(100 * target, color=MUTED, lw=1, ls="--")
    ax.text(1, 100 * target + 0.4, "95% target", fontsize=8, color=MUTED)
    ax.set_xlabel("test day", fontsize=8, color=MUTED); ax.set_ylabel("daily fill rate (%)", fontsize=8, color=MUTED)
    ax.set_title("Daily fill rate, one Monte Carlo run (same lead-time and demand draws)", loc="left", fontsize=10, color=INK)
    ax.legend(frameon=False, fontsize=8); _style(ax)
    fig.tight_layout(); fig.savefig(rep / "fig_daily_fill.png", dpi=140); plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 3.4))
    for k, n in enumerate(["base", "unwarned", "warned"]):
        ax.plot(np.arange(1, len(st_daily[n]) + 1), 100 * st_daily[n], color=SERIES[k], lw=2, label=n)
    sc = cfg["stress"]
    ax.axvspan(sc["from_day"] + 1, sc["to_day"], color=GRID, alpha=0.6, lw=0)
    ax.text(sc["from_day"] + 1.5, ax.get_ylim()[0] + 1, "slow FOODS_3 POs placed", fontsize=8, color=MUTED)
    ax.set_xlabel("test day", fontsize=8, color=MUTED); ax.set_ylabel("daily fill rate (%)", fontsize=8, color=MUTED)
    ax.set_title("Stress test: daily fill, recommended policy (one run, common random numbers)", loc="left", fontsize=10, color=INK)
    ax.legend(frameon=False, fontsize=8); _style(ax)
    fig.tight_layout(); fig.savefig(rep / "fig_stress.png", dpi=140); plt.close(fig)
    print("\n".join(md))
